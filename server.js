// 7. Synchronized & Plain Lyrics (lrclib.net)
app.get('/api/lyrics', async (req, res) => {
    const { title, artist } = req.query;
    if (!title) return res.json({ lyrics: null });

    // Clean title: remove "feat", "(Official Video)", "[Clip Officiel]", etc.
    const cleanTitle = title
        .replace(/\s*[\(\[](official\s*video|clip\s*officiel|audio|lyrics|paroles|remastered|hq|4k)[\)\]]/gi, '')
        .replace(/ft\..*$/i, '')
        .replace(/feat\..*$/i, '')
        .trim();

    const cacheKey = `${artist || ''}_${cleanTitle}`.toLowerCase();
    const cached = getCached(lyricsCache, cacheKey);
    if (cached) return res.json(cached);

    try {
        let url = `https://lrclib.net/api/get?track_name=${encodeURIComponent(cleanTitle)}`;
        if (artist) url += `&artist_name=${encodeURIComponent(artist)}`;

        let response = await fetch(url, { headers: { 'User-Agent': 'YouTubeMusicHomemade/1.0' } });
        let data = null;

        if (response.ok) {
            data = await response.json();
        } else {
            // Try search endpoint
            const searchUrl = `https://lrclib.net/api/search?q=${encodeURIComponent(`${cleanTitle} ${artist || ''}`)}`;
            const sRes = await fetch(searchUrl, { headers: { 'User-Agent': 'YouTubeMusicHomemade/1.0' } });
            if (sRes.ok) {
                const list = await sRes.json();
                if (Array.isArray(list) && list.length > 0) {
                    data = list[0];
                }
            }
        }

        if (!data || (!data.syncedLyrics && !data.plainLyrics)) {
            return res.json({ lyrics: null });
        }

        // Parse synchronized lyrics into [{ time: seconds, text: "..." }]
        let parsedSynced = [];
        if (data.syncedLyrics) {
            const lines = data.syncedLyrics.split('\n');
            const timeRegex = /\[(\d{2}):(\d{2})\.(\d{2,3})\](.*)/;
            for (const line of lines) {
                const match = timeRegex.exec(line);
                if (match) {
                    const mins = parseInt(match[1], 10);
                    const secs = parseInt(match[2], 10);
                    const ms = parseFloat('0.' + match[3]);
                    const time = mins * 60 + secs + ms;
                    const text = match[4].trim();
                    if (text) {
                        parsedSynced.push({ time, text });
                    }
                }
            }
        }

        const result = {
            syncedLyrics: parsedSynced.length > 0 ? parsedSynced : null,
            plainLyrics: data.plainLyrics || null,
            trackName: data.trackName || cleanTitle,
            artistName: data.artistName || artist,
        };

        setCache(lyricsCache, cacheKey, result, 24 * 60 * 60 * 1000);
        res.json(result);
    } catch (err) {
        console.error('Lyrics error:', err.message);
        res.json({ lyrics: null });
    }
});

// Translation API for lyrics (English / World -> French)
app.post('/api/lyrics/translate', async (req, res) => {
    const { lines, targetLang = 'fr' } = req.body;
    if (!Array.isArray(lines) || lines.length === 0) {
        return res.json({ translated: [] });
    }

    try {
        const results = [];
        // Batch translate up to 40 lines
        const slice = lines.slice(0, 50);
        for (const item of slice) {
            const rawText = (item.text || item).trim();
            if (!rawText) {
                results.push({ text: rawText, translated: '' });
                continue;
            }

            const cacheKey = rawText.toLowerCase();
            const cached = getCached(translationCache, cacheKey);
            if (cached) {
                results.push({ text: rawText, translated: cached });
                continue;
            }

            try {
                // Free MyMemory Translate API
                const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(rawText)}&langpair=autodetect|${targetLang}`;
                const resp = await fetch(url, { headers: { 'User-Agent': 'YouTubeMusicClone/3.6' } });
                if (resp.ok) {
                    const data = await resp.json();
                    const trans = data.responseData?.translatedText || rawText;
                    setCache(translationCache, cacheKey, trans, 7 * 24 * 3600 * 1000);
                    results.push({ text: rawText, translated: trans });
                    continue;
                }
            } catch (e) {}

            results.push({ text: rawText, translated: rawText });
        }
        res.json({ translated: results });
    } catch (err) {
        console.warn('Translation error:', err.message);
        res.json({ translated: [] });
    }
});

