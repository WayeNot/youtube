// Helper: Extract audio URL using fast in-memory cache + persistent DB + yt-dlp
async function getAudioStreamUrl(videoId) {
    const now = Date.now();
    // 1. Check in-memory cache
    const mem = streamCache.get(videoId);
    if (mem && mem.expiresAt > now) {
        return mem.url;
    }

    // 2. Check persistent DB cache (SQLite / Postgres)
    try {
        const dbCached = await db.getStreamCache(videoId);
        const cachedUrl = dbCached?.streamUrl || dbCached?.url;
        if (cachedUrl && dbCached.expiresAt > now) {
            streamCache.set(videoId, { url: cachedUrl, expiresAt: dbCached.expiresAt });
            return cachedUrl;
        }
    } catch (e) { }

    // 3. Return active in-flight extraction if already solving
    if (inFlightStreams.has(videoId)) {
        return inFlightStreams.get(videoId);
    }

    // 4. Ensure yt-dlp binary is ready and cookies file exists
    await ensureYtDlp();
    const hasCookies = syncCookiesFile();
    const cookiesPath = getCookiesPath();

    // Concurrency queue for yt-dlp to avoid CPU starvation
    const runYtDlp = (extraArgs = [], format = '18/bestaudio/ba/b', timeoutMs = 4500, targetUrl = null) => {
        return ytDlpQueue.run(() => {
            return new Promise((resolve, reject) => {
                const target = targetUrl || `https://www.youtube.com/watch?v=${videoId}`;
                const args = [
                    '-g',
                    '-f', format,
                    '--no-playlist',
                    '--no-warnings',
                    '--no-cache-dir',
                    '--no-check-certificates',
                    '--js-runtimes', `node:${process.execPath}`,
                    '--remote-components', 'ejs:github',
                    ...extraArgs,
                    '--',
                    target
                ];
                execFile(
                    YTDLP_PATH,
                    args,
                    { timeout: timeoutMs },
                    (err, stdout, stderr) => {
                        if (err) {
                            const errMsg = (stderr || stdout || err.message || '').trim();
                            return reject(new Error(errMsg));
                        }
                        const lines = stdout.trim().split('\n');
                        const streamUrl = lines[0]?.trim();
                        if (!streamUrl || !streamUrl.startsWith('http')) {
                            return reject(new Error('Invalid audio stream URL returned'));
                        }
                        resolve(streamUrl);
                    }
                );
            });
        });
    };

    // 5. Extract stream with yt-dlp: Web session with cookies first, then visionos, android, and web
    const streamPromise = (async () => {
        let lastErr = null;
        const format = '18/bestaudio/ba/b';
        const ua = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

        // Attempt 1: Authenticated session with desktop cookies
        if (hasCookies) {
            try {
                return await runYtDlp(['--cookies', cookiesPath, '--user-agent', ua, '--extractor-args', 'youtube:player_client=web'], format, 12000);
            } catch (err) {
                console.warn(`yt-dlp cookies web attempt failed for ${videoId}: ${err.message}. Retrying visionos...`);
                lastErr = err;
            }
        }

        // Attempt 2: VisionOS client (fast, reliable, uncluttered audio stream extraction)
        try {
            return await runYtDlp(['--extractor-args', 'youtube:player_client=visionos'], 'bestaudio/140/251/18/ba/b', 6000);
        } catch (err) {
            console.warn(`yt-dlp visionos attempt failed for ${videoId}: ${err.message}. Retrying android...`);
            lastErr = err;
        }

        // Attempt 3: Android client
        try {
            return await runYtDlp(['--extractor-args', 'youtube:player_skip=configs;player_client=android'], format, 6000);
        } catch (err) {
            console.warn(`yt-dlp android attempt failed for ${videoId}: ${err.message}. Retrying default web...`);
            lastErr = err;
        }

        // Attempt 4: Default fallback
        try {
            return await runYtDlp([], format, 6000);
        } catch (err) {
            lastErr = err;
        }

        // Attempt 5: Smart Fallback for Music Premium only or unavailable videos (e.g. WMojuNvJtCo, wBli7itfyYg, _8DXhtXXTVg, OO2kPK5-qno)
        // Find public audio / official track on YouTube via oEmbed + Innertube resolution
        try {
            const oembedRes = await fetch(`https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${videoId}&format=json`);
            let query = '';
            if (oembedRes.ok) {
                const oembedData = await oembedRes.json();
                const title = (oembedData.title || '').replace(/- Topic$/i, '').trim();
                const author = (oembedData.author_name || '').replace(/- Topic$/i, '').trim();
                if (title) {
                    query = author ? `${author} ${title} audio` : `${title} audio`;
                }
            }

            if (query) {
                console.log(`⚡ Recherche alternative pour titre restreint (${videoId}): "${query}"...`);
                const searchResults = await searchInnertube(query);
                for (const altVideo of searchResults) {
                    const altId = altVideo?.id || altVideo?.videoId;
                    if (altId && altId !== videoId) {
                        console.log(`⚡ Titre alternatif testé: ${altId} (${altVideo.title})`);
                        const altTarget = `https://www.youtube.com/watch?v=${altId}`;
                        try {
                            if (hasCookies) {
                                try {
                                    return await runYtDlp(['--cookies', cookiesPath, '--user-agent', ua, '--extractor-args', 'youtube:player_client=web'], format, 8000, altTarget);
                                } catch (e) {}
                            }
                            return await runYtDlp(['--extractor-args', 'youtube:player_client=visionos'], 'bestaudio/140/251/18/ba/b', 6000, altTarget);
                        } catch (altErr) {
                            console.warn(`Alternative ${altId} extraction failed:`, altErr.message);
                        }
                    }
                }
            }
        } catch (oembedErr) {
            console.warn(`Smart audio fallback search failed for ${videoId}:`, oembedErr.message);
        }

        console.error(`yt-dlp all attempts failed for ${videoId}: ${lastErr?.message}`);
        throw lastErr || new Error('All stream extraction attempts failed');
    })().then(async (streamUrl) => {
        inFlightStreams.delete(videoId);
        // 5 hours TTL for persistent stream URL
        const ttl = Math.max(config.cacheTtl.stream, 5 * 3600 * 1000);
        const expiresAt = Date.now() + ttl;
        // Save to instance in-memory cache
        streamCache.set(videoId, { url: streamUrl, expiresAt });
        // Persist to database cache
        try {
            await db.setStreamCache(videoId, streamUrl, expiresAt);
        } catch (e) { }
        return streamUrl;
    }).catch((err) => {
        inFlightStreams.delete(videoId);
        throw err;
    });

    inFlightStreams.set(videoId, streamPromise);
    return streamPromise;
}

// Helper: Search via YouTube Innertube WEB API
async function searchInnertube(query) {
    try {
        const res = await fetch('https://www.youtube.com/youtubei/v1/search', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'User-Agent':
                    'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36',
            },
            body: JSON.stringify({
                context: {
                    client: {
                        clientName: 'WEB',
                        clientVersion: '2.20240401.01.00',
                        hl: 'fr',
                        gl: 'FR',
                    },
                },
                query: query,
            }),
        });

        if (!res.ok) throw new Error(`Innertube HTTP ${res.status}`);
        const data = await res.json();
        const contents =
            data?.contents?.twoColumnSearchResultsRenderer?.primaryContents
                ?.sectionListRenderer?.contents?.[0]?.itemSectionRenderer?.contents ||
            [];

        const results = [];
        for (const item of contents) {
            const vr = item.videoRenderer;
            if (vr && vr.videoId) {
                const title = vr.title?.runs?.map((r) => r.text).join('') || '';
                const artist =
                    vr.ownerText?.runs?.map((r) => r.text).join('') || 'Artiste inconnu';
                const duration = vr.lengthText?.simpleText || '3:30';
                const views = vr.shortViewCountText?.simpleText || '';
                const thumb =
                    vr.thumbnail?.thumbnails?.slice(-1)[0]?.url ||
                    `https://i.ytimg.com/vi/${vr.videoId}/hqdefault.jpg`;

                const publishedTime = vr.publishedTimeText?.simpleText || '';
                const channelAvatar = vr.channelThumbnailSupportedRenderers?.channelThumbnailWithLinkRenderer?.thumbnail?.thumbnails?.[0]?.url || `https://api.dicebear.com/7.x/identicon/svg?seed=${encodeURIComponent(artist)}`;

                // Calculate duration in seconds
                const parts = duration.split(':').map(Number);
                let durationSec = 0;
                if (parts.length === 2) durationSec = parts[0] * 60 + parts[1];
                else if (parts.length === 3)
                    durationSec = parts[0] * 3600 + parts[1] * 60 + parts[2];

                results.push({
                    id: vr.videoId,
                    title,
                    artist,
                    channel: artist,
                    duration,
                    durationSec,
                    thumbnail: thumb,
                    views,
                    publishedTime,
                    channelAvatar,
                });
            }
        }
        return results;
    } catch (err) {
        console.error('Innertube search failed, falling back to yt-dlp:', err.message);
        return null;
    }
}

// Fallback: Search via yt-dlp flat playlist
function searchYtDlp(query, limit = 20) {
    return new Promise(async (resolve) => {
        await ensureYtDlp();
        execFile(
            YTDLP_PATH,
            ['--dump-json', '--flat-playlist', '--', `ytsearch${limit}:${query}`],
            { timeout: 15000 },
            (err, stdout) => {
                if (err || !stdout) return resolve([]);
                const results = [];
                const lines = stdout.trim().split('\n');
                for (const line of lines) {
                    try {
                        const item = JSON.parse(line);
                        if (item && item.id) {
                            const durSec = item.duration || 0;
                            const mins = Math.floor(durSec / 60);
                            const secs = Math.floor(durSec % 60)
                                .toString()
                                .padStart(2, '0');
                            const durStr = durSec > 0 ? `${mins}:${secs}` : '3:30';
                            results.push({
                                id: item.id,
                                title: item.title || 'Sans titre',
                                artist: item.uploader || item.channel || 'Artiste inconnu',
                                duration: durStr,
                                durationSec: durSec,
                                thumbnail:
                                    item.thumbnails?.slice(-1)[0]?.url ||
                                    `https://i.ytimg.com/vi/${item.id}/hqdefault.jpg`,
                                views: item.view_count
                                    ? `${(item.view_count / 1000000).toFixed(1)} M de vues`
                                    : '',
                            });
                        }
                    } catch (e) { }
                }
                resolve(results);
            }
        );
    });
}

// Main Search Function
async function performSearch(query, limit = 20) {
    const cached = getCached(searchCache, query);
    if (cached) return cached;

    let results = await searchInnertube(query);
    if (!results || results.length === 0) {
        results = await searchYtDlp(query, limit);
    }

    // Cache for 15 minutes
    if (results && results.length > 0) {
        setCache(searchCache, query, results, 15 * 60 * 1000);
    }
    return results || [];
}

