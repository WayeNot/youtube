// Helper: Ensure cookies.txt is created from environment variables if present
function syncCookiesFile() {
    const fs = require('fs');
    const cookiesPath = getCookiesPath();
    try {
        if (process.env.YTDLP_COOKIES_BASE64 && process.env.YTDLP_COOKIES_BASE64.trim()) {
            const decoded = Buffer.from(process.env.YTDLP_COOKIES_BASE64.trim(), 'base64').toString('utf-8');
            if (decoded.length > 20) {
                fs.writeFileSync(cookiesPath, decoded, 'utf-8');
                return true;
            }
        }
        if (process.env.YTDLP_COOKIES && process.env.YTDLP_COOKIES.trim()) {
            fs.writeFileSync(cookiesPath, process.env.YTDLP_COOKIES.trim(), 'utf-8');
            return true;
        }
        // If cookies.txt is bundled in the repository, copy it
        const bundledCookies = path.join(__dirname, 'cookies.txt');
        if (cookiesPath !== bundledCookies && fs.existsSync(bundledCookies)) {
            try {
                fs.copyFileSync(bundledCookies, cookiesPath);
                return true;
            } catch (e) {
                console.warn('⚠️ Échec copie bundled cookies.txt vers /tmp:', e.message);
            }
        }
        // Embedded cookies fallback
        if (!fs.existsSync(cookiesPath) || fs.statSync(cookiesPath).size < 10) {
            fs.writeFileSync(cookiesPath, EMBEDDED_COOKIES, 'utf-8');
            return true;
        }
    } catch (e) {
        console.error('❌ Erreur écriture cookies.txt:', e.message);
    }
    return fs.existsSync(cookiesPath) && fs.statSync(cookiesPath).size > 10;
}

// Simple concurrency limiter for yt-dlp to protect server CPU/RAM
const ytDlpQueue = {
    running: 0,
    maxConcurrent: 4,
    queue: [],
    run(task) {
        return new Promise((resolve, reject) => {
            this.queue.push({ task, resolve, reject });
            this.next();
        });
    },
    next() {
        if (this.running >= this.maxConcurrent || this.queue.length === 0) return;
        this.running++;
        const { task, resolve, reject } = this.queue.shift();
        Promise.resolve(task())
            .then(resolve)
            .catch(reject)
            .finally(() => {
                this.running--;
                this.next();
            });
    }
};

// In-flight extraction promises map to avoid duplicate concurrent yt-dlp processes
