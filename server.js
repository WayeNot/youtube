// Native HTTPS streaming file downloader (0.9s, works in minimal serverless containers without curl)
function downloadFile(url, dest) {
    const fs = require('fs');
    const https = require('https');
    return new Promise((resolve, reject) => {
        https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)' } }, (res) => {
            if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
                return downloadFile(res.headers.location, dest).then(resolve).catch(reject);
            }
            if (res.statusCode !== 200) {
                return reject(new Error('HTTP ' + res.statusCode));
            }
            const file = fs.createWriteStream(dest);
            res.pipe(file);
            file.on('finish', () => {
                file.close(() => {
                    try { fs.chmodSync(dest, 0o755); } catch (_) {}
                    resolve();
                });
            });
            file.on('error', (err) => {
                try { fs.unlinkSync(dest); } catch (_) {}
                reject(err);
            });
        }).on('error', reject);
    });
}

// Ensure yt-dlp standalone Linux binary and cookies are present and healthy
let ytDlpPromise = null;
async function ensureYtDlp() {
    if (ytDlpPromise) {
        try {
            const fs = require('fs');
            if (fs.existsSync(YTDLP_PATH) && fs.statSync(YTDLP_PATH).size >= 35000000) {
                return ytDlpPromise;
            }
        } catch (_) {}
        ytDlpPromise = null;
    }

    ytDlpPromise = (async () => {
        const fs = require('fs');
        const isServerless = !!(process.env.VERCEL || process.env.AWS_LAMBDA_FUNCTION_NAME);
        const bundledPath = path.join(__dirname, 'bin', YTDLP_BIN_NAME);
        const tmpPath = path.join('/tmp', YTDLP_BIN_NAME);

        let targetPath = isServerless ? tmpPath : (fs.existsSync(bundledPath) ? bundledPath : tmpPath);

        if (isServerless) {
            let needsBinary = !fs.existsSync(tmpPath) || fs.statSync(tmpPath).size < 35000000;
            if (!needsBinary) {
                try {
                    const { execFileSync } = require('child_process');
                    execFileSync(tmpPath, ['--version'], { timeout: 2500, stdio: 'pipe' });
                } catch (testErr) {
                    console.warn('⚠️ Existing /tmp/yt-dlp is not a working standalone binary, deleting:', testErr.message);
                    needsBinary = true;
                    try { fs.unlinkSync(tmpPath); } catch (e) {}
                }
            }

            if (needsBinary) {
                if (fs.existsSync(bundledPath) && fs.statSync(bundledPath).size >= 35000000) {
                    try {
                        console.log('📦 Copie de yt-dlp depuis le bundle vers /tmp/yt-dlp...');
                        fs.copyFileSync(bundledPath, tmpPath);
                        fs.chmodSync(tmpPath, 0o755);
                        needsBinary = false;
                    } catch (e) {
                        console.warn('⚠️ Échec copie bundled yt-dlp vers /tmp:', e.message);
                    }
                }
                if (needsBinary) {
                    console.log('⬇️ Téléchargement direct de yt-dlp_linux standalone vers /tmp/yt-dlp via HTTPS...');
                    try {
                        await downloadFile('https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp_linux', tmpPath);
                        fs.chmodSync(tmpPath, 0o755);
                        console.log('✅ yt-dlp standalone téléchargé avec succès ! Taille:', fs.statSync(tmpPath).size);
                    } catch (e) {
                        console.error('❌ Échec du téléchargement natif de yt-dlp:', e.message);
                    }
                }
            } else {
                try { fs.chmodSync(tmpPath, 0o755); } catch (e) {}
            }
            targetPath = tmpPath;
        } else {
            // Local development
            if (!fs.existsSync(bundledPath) || fs.statSync(bundledPath).size < 35000000) {
                const binDir = path.dirname(bundledPath);
                if (!fs.existsSync(binDir)) fs.mkdirSync(binDir, { recursive: true });
                try {
                    await downloadFile('https://github.com/yt-dlp/yt-dlp/releases/latest/download/yt-dlp_linux', bundledPath);
                    fs.chmodSync(bundledPath, 0o755);
                } catch (e) {
                    console.error('❌ Échec téléchargement local yt-dlp:', e.message);
                }
            } else {
                try { fs.chmodSync(bundledPath, 0o755); } catch (e) {}
            }
            targetPath = fs.existsSync(bundledPath) ? bundledPath : tmpPath;
        }

        YTDLP_PATH = targetPath;
        const hasCookies = syncCookiesFile();
        if (hasCookies) {
            const cookiesPath = getCookiesPath();
            console.log('🍪 Cookies YouTube actifs ! Taille:', fs.statSync(cookiesPath).size, 'octets');
        } else {
            console.log('⚠️ Aucun cookie YouTube détecté');
        }
        return targetPath;
    })();
    return ytDlpPromise;
}

