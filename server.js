app.post('/api/auth/register', async (req, res) => {
    const { username, password } = req.body || {};
    if (!username || !password) {
        return res.status(400).json({ error: 'Nom d\'utilisateur et mot de passe requis' });
    }
    const cleanUsername = String(username).trim();
    if (cleanUsername.length < 3 || cleanUsername.length > 30) {
        return res.status(400).json({ error: 'Le pseudo doit comporter entre 3 et 30 caractères.' });
    }
    if (!/^[a-zA-Z0-9_\-\.]+$/.test(cleanUsername)) {
        return res.status(400).json({ error: 'Le pseudo ne peut contenir que des lettres, chiffres, tirets et points.' });
    }
    if (typeof password !== 'string' || password.length < 6) {
        return res.status(400).json({ error: 'Le mot de passe doit comporter au moins 6 caractères pour des raisons de sécurité.' });
    }

    try {
        const existing = await db.findUserByUsername(cleanUsername);
        if (existing) {
            return res.status(409).json({ error: 'Ce nom d\'utilisateur est déjà pris' });
        }

        const salt = await bcrypt.genSalt(10);
        const passwordHash = await bcrypt.hash(password, salt);
        const userId = crypto.randomUUID();
        const now = Date.now();

        await db.createUser(userId, cleanUsername, passwordHash, now);

        const token = jwt.sign({ id: userId, username: cleanUsername }, config.jwtSecret, { expiresIn: '30d' });

        res.json({
            success: true,
            token,
            user: { id: userId, username: cleanUsername, role: 'user' },
            data: { favorites: [], playlists: [], history: [], recent_searches: [], settings: {} }
        });
    } catch (err) {
        console.error('Register error:', err);
        res.status(500).json({ error: 'Erreur lors de la création du compte' });
    }
});

// 2. Login User
app.post('/api/auth/login', async (req, res) => {
    const { username, password } = req.body || {};
    if (!username || !password) {
        return res.status(400).json({ error: 'Nom d\'utilisateur et mot de passe requis' });
    }
    const cleanUsername = String(username).trim();
    const clientIp = req.headers['x-forwarded-for'] || req.socket.remoteAddress || 'unknown-ip';
    const rateLimitKey = `${clientIp}_${cleanUsername.toLowerCase()}`;

    // Rate limit check
    const rateLimitStatus = checkLoginRateLimit(rateLimitKey);
    if (!rateLimitStatus.allowed) {
        return res.status(429).json({ error: rateLimitStatus.message });
    }

    try {
        const user = await db.findUserByUsername(cleanUsername);
        if (!user) {
            recordLoginFailure(rateLimitKey);
            return res.status(401).json({ error: 'Nom d\'utilisateur ou mot de passe incorrect' });
        }

        const isMatch = await bcrypt.compare(password, user.password_hash);
        if (!isMatch) {
            recordLoginFailure(rateLimitKey);
            return res.status(401).json({ error: 'Nom d\'utilisateur ou mot de passe incorrect' });
        }

        // Login succeeded, clear failures
        clearLoginFailures(rateLimitKey);

        const token = jwt.sign({ id: user.id, username: user.username, role: user.role || 'user' }, config.jwtSecret, { expiresIn: '30d' });

        // Fetch user saved data
        const userData = (await db.getUserData(user.id)) || {
            favorites: [],
            playlists: [],
            history: [],
            recent_searches: [],
            settings: {}
        };

        res.json({
            success: true,
            token,
            user: { id: user.id, username: user.username, avatar: user.avatar || '', role: user.role || 'user' },
            data: userData
        });
    } catch (err) {
        console.error('Login error:', err);
        res.status(500).json({ error: 'Erreur lors de la connexion' });
    }
});

