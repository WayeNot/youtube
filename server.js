function getCached(cache, key) {
    const item = cache.get(key);
    if (item && item.expiresAt > Date.now()) {
        return item.data;
    }
    cache.delete(key);
    return null;
}

function setCache(cache, key, data, ttlMs) {
    cache.set(key, { data, expiresAt: Date.now() + ttlMs });
}

